'use strict';
const fs=require('node:fs');
const cp=require('node:child_process');
const crypto=require('node:crypto');
const assert=require('node:assert/strict');
const args=process.argv.slice(2);
const option=name=>args[args.indexOf(name)+1];
const config=JSON.parse(fs.readFileSync(process.env.THESIS_AB_CONTROL,'utf8'));
assert(['fifo','latest'].includes(config.profile));
assert([0,100000].includes(config.sleep_us));
const w=Number(option('--width')),h=Number(option('--height')),fps=Number(option('--fps'));
assert.equal(w,1280);assert.equal(h,704);assert.equal(fps,15);
const queue=config.profile==='fifo'?'max-size-buffers=0 max-size-bytes=0 max-size-time=0 leaky=no':'max-size-buffers=2 max-size-bytes=0 max-size-time=0 leaky=downstream';
const pipeline=`shmsrc socket-path=${option('--socket')} is-live=true do-timestamp=true ! video/x-raw,format=${option('--format')},width=${w},height=${h},framerate=${fps}/1 ! queue name=ab_queue ${queue} ! identity name=ab_delay sleep-time=${config.sleep_us} ! videoconvert ! video/x-raw,format=I420 ! vp8enc name=ab_encoder deadline=1 cpu-used=8 target-bitrate=2500000 keyframe-max-dist=${option('--keyframe')} ! rtpvp8pay pt=96 ssrc=2 mtu=1200 ! application/x-rtp,media=video,encoding-name=VP8,payload=96,clock-rate=90000`;
assert(Buffer.byteLength(pipeline)<980,'WHIP client video pipeline capacity');
fs.writeFileSync(config.pipeline_path,JSON.stringify({profile:config.profile,sleep_us:config.sleep_us,pipeline,pipeline_sha256:crypto.createHash('sha256').update(pipeline).digest('hex'),instrumentation_binary:config.binary},null,2)+'\n',{mode:0o600,flag:'wx'});
const child=cp.spawn(config.binary,['-n','-u',option('--url'),'-t',option('--token'),'-V',pipeline],{env:{...process.env,THESIS_AB_LOG:config.log_path},stdio:'inherit'});
fs.writeFileSync(config.pid_path,String(child.pid)+'\n',{mode:0o600,flag:'wx'});
for(const signal of ['SIGTERM','SIGINT'])process.on(signal,()=>child.kill(signal));
child.on('error',e=>{console.error(e.message);process.exitCode=1;});
child.on('exit',(code,signal)=>{process.exitCode=code===null?(signal?1:0):code;});
